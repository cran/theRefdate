test_that("ohne setFlavour() rechnet theRefdate wie die CRAN-Fassung 1.0.0 (Format TT.MM.JJJJ)", {
  expect_equal(jahr(eingaben),  erwartet_jahr)
  expect_equal(monat(eingaben), erwartet_monat)
  expect_equal(tag(eingaben),   erwartet_tag)
})

test_that("dateAddMonths rechnet wie 1.0.0", {
  for (x in names(erwartet_add)) {
    erg <- vapply(monate, function(m) dateAddMonths(x, m), character(1))
    expect_equal(erg, erwartet_add[[x]], info = x)
  }
})

test_that("dateDiff rechnet wie 1.0.0", {
  for (k in names(erwartet_diff)) {
    teile <- strsplit(k, "|", fixed = TRUE)[[1]]
    r <- dateDiff(teile[1], teile[2])
    expect_equal(c(r$diffJ, r$diffM, r$diffDauer, r$diffDauerM), erwartet_diff[[k]], info = k)
  }
})

test_that("bewusste Abweichung von 1.0.0: NA und leerer String ergeben einen Fehler statt NA", {
  expect_error(jahr(NA_character_),  "Argument 'datumstring'")
  expect_error(monat(""),            "Argument 'datumstring'")
  expect_error(suppressWarnings(tag("kein Datum")), "Argument 'datumstring'")
  expect_error(dateDiff(NA_character_, "01.01.2000"), "Argument 'frueher'")
  expect_error(dateAddMonths(NA_character_, 1),       "Argument 'termin'")
})
